def generate_script(cfg: TrainingConfig, output_path: str | Path, colab: bool = False) -> str:
    """Generate a training script from config."""
    from backend.app import config as app_config
    from backend.app.services import datasets as ds_service

    dataset_dir = ds_service.dataset_dir(cfg.dataset_version)
    if not dataset_dir.is_absolute():
        dataset_dir = app_config.ROOT / dataset_dir

    template = COLAB_TEMPLATE if colab else TRAIN_SCRIPT_TEMPLATE

    script = template.format(
        run_name=cfg.run_name,
        config_json=json.dumps(cfg.to_dict(), indent=2, ensure_ascii=False),
        config_yaml=cfg.run_name + ".yaml",
        load_in_4bit=str(cfg.quantization.load_in_4bit),
        quant_type=cfg.quantization.quant_type,
        double_quant=str(cfg.quantization.double_quant),
        lora_r=cfg.lora.r,
        lora_alpha=cfg.lora.alpha,
        lora_dropout=cfg.lora.dropout,
        target_modules=repr(cfg.lora.target_modules),
        epochs=cfg.train.epochs,
        batch_size=cfg.train.per_device_batch_size,
        grad_accum=cfg.train.grad_accum,
        learning_rate=cfg.train.learning_rate,
        lr_scheduler=cfg.train.lr_scheduler,
        warmup_ratio=cfg.train.warmup_ratio,
        eval_steps=cfg.train.eval_steps,
        save_steps=cfg.train.save_steps,
        max_seq_length=cfg.train.max_seq_length,
        loss_masking=cfg.loss_masking,
        dataset_dir=str(dataset_dir),
    )

    output = Path(output_path)
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(script, encoding="utf-8")
    output.chmod(0o755)
    return script


def main():
    parser = argparse.ArgumentParser(description="Generate training script from config YAML")
    parser.add_argument("--config", required=True, help="Path to config YAML")
    parser.add_argument("--output", default=None, help="Output path (default: runs/<run_name>/train.py)")
    parser.add_argument("--colab", action="store_true", help="Generate Colab notebook variant")
    args = parser.parse_args()

    cfg = TrainingConfig.load_yaml(args.config)
    errors = cfg.validate()
    if errors:
        print("Config validation failed:")
        for e in errors:
            print(f"  - {e}")
        sys.exit(1)

    if args.output:
        output_path = args.output
    else:
        output_path = f"runs/{cfg.run_name}/train.py"

    generate_script(cfg, output_path, colab=args.colab)
    print(f"Generated: {output_path}")


if __name__ == "__main__":
    main()
