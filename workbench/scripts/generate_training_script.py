# Template for a standalone training script using standard PEFT
TRAIN_SCRIPT_TEMPLATE = '''#!/usr/bin/env python3
"""Auto-generated training script for run: {run_name}

Generated by scripts/generate_training_script.py
Config: {config_yaml}

Notes (plan 03):
- Output layout is the run directory itself (plan 03 §9): adapter/, tokenizer/,
  metrics.jsonl, checkpoints/, best_checkpoint.txt.
- Loss masking is template-agnostic: only the tokens added by each assistant
  turn are labelled (plan 03 PF3 — never learn system/user/tool tokens).
- metrics.jsonl is appended at every logged step (runner UI, plan 03 §7).
- If a checkpoint exists the run resumes from the latest one (Colab safety).
"""
import hashlib
import json
import os
import platform
import subprocess
import sys
import time
from pathlib import Path

import torch
from torch.utils.data import Dataset
from transformers import (
    AutoModelForCausalLM,
    AutoTokenizer,
    BitsAndBytesConfig,
    EarlyStoppingCallback,
    Trainer,
    TrainerCallback,
    TrainingArguments,
)
from peft import LoraConfig, get_peft_model, prepare_model_for_kbit_training, TaskType

IGNORE_INDEX = -100

# ── Config ─────────────────────────────────────────────────────────────────

CONFIG = {config_json}

RUN_NAME = CONFIG["run_name"]
BASE_MODEL = CONFIG["base_model"]
DATASET_VERSION = CONFIG["dataset_version"]
SEED = CONFIG["seed"]
MAX_SEQ_LENGTH = CONFIG["train"]["max_seq_length"]

# Run directory == cwd (the launcher sets it); outputs go straight in here.
OUTPUT_DIR = Path(".")
CHECKPOINT_DIR = OUTPUT_DIR / "checkpoints"
METRICS_PATH = OUTPUT_DIR / "metrics.jsonl"
OUTPUT_DIR.mkdir(parents=True, exist_ok=True)

# ── Quantization ─────────────────────────────────────────────────────────────

USE_BF16 = bool(torch.cuda.is_available() and torch.cuda.is_bf16_supported())
COMPUTE_DTYPE = torch.bfloat16 if USE_BF16 else torch.float16
quant_config = BitsAndBytesConfig(
    load_in_4bit={load_in_4bit},
    bnb_4bit_quant_type="{quant_type}",
    bnb_4bit_use_double_quant={double_quant},
    bnb_4bit_compute_dtype=COMPUTE_DTYPE,
)

# ── Model ────────────────────────────────────────────────────────────────────

print(f"Loading model: {{BASE_MODEL}}")
model = AutoModelForCausalLM.from_pretrained(
    BASE_MODEL,
    quantization_config=quant_config,
    device_map="auto",
    trust_remote_code=True,
)
model.config.use_cache = False
model = prepare_model_for_kbit_training(model, use_gradient_checkpointing=True)

tokenizer = AutoTokenizer.from_pretrained(BASE_MODEL, trust_remote_code=True)
tokenizer.pad_token = tokenizer.eos_token
tokenizer.padding_side = "right"

# ── LoRA ─────────────────────────────────────────────────────────────────────

lora_config = LoraConfig(
    r={lora_r},
    lora_alpha={lora_alpha},
    lora_dropout={lora_dropout},
    target_modules={target_modules},
    bias="none",
    task_type=TaskType.CAUSAL_LM,
)
model = get_peft_model(model, lora_config)
model.print_trainable_parameters()

# ── Dataset ─────────────────────────────────────────────────────────────────

DATASET_DIR = Path("{dataset_dir}")
train_path = DATASET_DIR / "train.jsonl"
val_path = DATASET_DIR / "val.jsonl"

def load_jsonl(path):
    with open(path, "r", encoding="utf-8") as f:
        return [json.loads(line) for line in f if line.strip()]

train_data = load_jsonl(train_path)
val_data = load_jsonl(val_path)
if not train_data or not val_data:
    raise RuntimeError("training and validation datasets must both be non-empty")

# Reproducibility artifacts (plan 03 §9).
(OUTPUT_DIR / "config.yaml").write_text(json.dumps(CONFIG, indent=2, ensure_ascii=False) + "\\n", encoding="utf-8")
source_manifest = DATASET_DIR / "manifest.json"
if source_manifest.exists():
    import shutil
    shutil.copy2(source_manifest, OUTPUT_DIR / "dataset_manifest.json")
script_hash = hashlib.sha256(Path(__file__).read_bytes()).hexdigest()
run_manifest = {{
    "run_name": RUN_NAME, "base_model": BASE_MODEL, "dataset_version": DATASET_VERSION,
    "seed": SEED, "script_sha256": script_hash, "created_at": time.time(),
    "python": sys.version, "platform": platform.platform(),
}}
(OUTPUT_DIR / "run_manifest.json").write_text(json.dumps(run_manifest, indent=2), encoding="utf-8")
try:
    freeze = subprocess.run([sys.executable, "-m", "pip", "freeze"], capture_output=True, text=True, timeout=30)
    (OUTPUT_DIR / "env.txt").write_text(freeze.stdout if freeze.returncode == 0 else freeze.stderr, encoding="utf-8")
except Exception as exc:
    (OUTPUT_DIR / "env.txt").write_text(f"pip freeze unavailable: {{exc}}\\n", encoding="utf-8")

print(f"Loaded {{len(train_data)}} train, {{len(val_data)}} val examples")

# ── Loss masking: assistant turns only (plan 03 PF3) ────────────────────────
# Template-agnostic: render the conversation incrementally and label only the
# tokens added by each assistant turn. No hard-coded role markers, so this
# works for any chat template (Hermes ChatML, Qwen, ...).

LOSS_MASKING = "{loss_masking}"

def _render_ids(messages, tools, n):
    return tokenizer.apply_chat_template(
        messages[:n],
        tools=tools,
        tokenize=True,
        add_generation_prompt=False,
    )

def build_example(example):
    """Return (input_ids, labels); labels are IGNORE_INDEX except on
    assistant-turn tokens (all assistant turns, not just the final one)."""
    messages = example.get("messages", [])
    tools = example.get("tools")
    full_ids = _render_ids(messages, tools, len(messages))
    if LOSS_MASKING == "all":
        return list(full_ids), list(full_ids)
    labels = [IGNORE_INDEX] * len(full_ids)
    for i, m in enumerate(messages):
        if m.get("role") != "assistant":
            continue
        start = 0 if i == 0 else len(_render_ids(messages, tools, i))
        end = min(len(_render_ids(messages, tools, i + 1)), len(full_ids))
        if end > start:
            labels[start:end] = full_ids[start:end]
    return list(full_ids), labels

class MaskedDataset(Dataset):
    def __init__(self, examples):
        self.items = [build_example(e) for e in examples]
        print(f"  pre-tokenized {{len(self.items)}} examples")

    def __len__(self):
        return len(self.items)

    def __getitem__(self, i):
        input_ids, labels = self.items[i]
        return {{
            "input_ids": input_ids,
            "labels": labels,
            "attention_mask": [1] * len(input_ids),
        }}

PAD_ID = tokenizer.pad_token_id if tokenizer.pad_token_id is not None else 0

def masked_collate_fn(batch):
    max_len = min(max(len(b["input_ids"]) for b in batch), MAX_SEQ_LENGTH)
    input_ids, labels, attention_mask = [], [], []
    for b in batch:
        ids = b["input_ids"][:max_len]
        lab = b["labels"][:max_len]
        pad_n = max_len - len(ids)
        input_ids.append(ids + [PAD_ID] * pad_n)
        labels.append(lab + [IGNORE_INDEX] * pad_n)
        attention_mask.append([1] * len(ids) + [0] * pad_n)
    return {{
        "input_ids": torch.tensor(input_ids, dtype=torch.long),
        "labels": torch.tensor(labels, dtype=torch.long),
        "attention_mask": torch.tensor(attention_mask, dtype=torch.long),
    }}

train_ds = MaskedDataset(train_data)
val_ds = MaskedDataset(val_data)

# ── Metrics logging (plan 03 §7) ────────────────────────────────────────────

class MetricsLogger(TrainerCallback):
    """Append every logged step to metrics.jsonl for the workbench UI."""

    def __init__(self, path):
        self.path = Path(path)
        self.t0 = None

    def on_train_begin(self, args, state, control, **kwargs):
        self.t0 = time.time()

    def on_log(self, args, state, control, logs=None, **kwargs):
        if logs is None:
            return
        entry = {{
            "step": state.global_step,
            "train_loss": logs.get("loss"),
            "eval_loss": logs.get("eval_loss"),
            "learning_rate": logs.get("learning_rate"),
            "grad_norm": logs.get("grad_norm"),
            "epoch": state.epoch,
            "elapsed_seconds": (time.time() - self.t0) if self.t0 else None,
        }}
        entry = {{k: v for k, v in entry.items() if v is not None}}
        with open(self.path, "a", encoding="utf-8") as f:
            f.write(json.dumps(entry, ensure_ascii=False) + "\\n")

# ── Training arguments ───────────────────────────────────────────────────────

steps_per_epoch = max(1, (len(train_data) + {batch_size} * {grad_accum} - 1) // ({batch_size} * {grad_accum}))
EVAL_SAVE_STEPS = max(1, min({eval_steps}, {save_steps}, steps_per_epoch))

training_args = TrainingArguments(
    output_dir=str(CHECKPOINT_DIR),
    num_train_epochs={epochs},
    per_device_train_batch_size={batch_size},
    per_device_eval_batch_size={batch_size},
    gradient_accumulation_steps={grad_accum},
    learning_rate={learning_rate},
    lr_scheduler_type="{lr_scheduler}",
    warmup_ratio={warmup_ratio},
    logging_steps=10,
    eval_strategy="steps",
    eval_steps=EVAL_SAVE_STEPS,
    save_strategy="steps",
    save_steps=EVAL_SAVE_STEPS,
    save_total_limit=3,
    load_best_model_at_end=True,
    metric_for_best_model="eval_loss",
    greater_is_better=False,
    fp16=not USE_BF16,
    bf16=USE_BF16,
    max_grad_norm=1.0,
    report_to="none",
    seed=SEED,
    data_seed=SEED,
)

# ── Trainer ──────────────────────────────────────────────────────────────────

trainer = Trainer(
    model=model,
    args=training_args,
    train_dataset=train_ds,
    eval_dataset=val_ds,
    data_collator=masked_collate_fn,
    callbacks=[
        MetricsLogger(METRICS_PATH),
        EarlyStoppingCallback(early_stopping_patience={early_stopping_patience}),
    ],
)

# ── Train (resume from latest checkpoint when present) ──────────────────────

resume_from = None
if CHECKPOINT_DIR.exists():
    existing = sorted(
        (p for p in CHECKPOINT_DIR.glob("checkpoint-*") if p.name.rsplit("-", 1)[-1].isdigit()),
        key=lambda p: int(p.name.rsplit("-", 1)[-1]),
    )
    if existing:
        resume_from = str(existing[-1])
        print(f"Resuming from checkpoint: {{resume_from}}")

print("Starting training...")
trainer.train(resume_from_checkpoint=resume_from)

# ── Save ───────────────────────────────────────────────────────────────────

print("Saving adapter...")
trainer.save_model(str(OUTPUT_DIR / "adapter"))
tokenizer.save_pretrained(str(OUTPUT_DIR / "tokenizer"))
trainer.save_state()

# Point best_checkpoint.txt at the checkpoint closest to the best eval loss.
best_step = None
for log in reversed(getattr(trainer.state, "log_history", [])):
    if "eval_loss" in log and log.get("step") is not None:
        best_step = int(log["step"])
        break
candidates = sorted(
    (p for p in CHECKPOINT_DIR.glob("checkpoint-*") if p.name.rsplit("-", 1)[-1].isdigit()),
    key=lambda p: int(p.name.rsplit("-", 1)[-1]),
)
best_path = min(candidates, key=lambda p: abs(int(p.name.rsplit("-", 1)[-1]) - best_step)) if candidates and best_step else (candidates[-1] if candidates else None)
if best_path is not None:
    (OUTPUT_DIR / "best_checkpoint.txt").write_text(str(best_path), encoding="utf-8")

history = getattr(trainer.state, "log_history", [])
eval_history = [entry for entry in history if "eval_loss" in entry]
best_eval = min((float(entry["eval_loss"]) for entry in eval_history), default=None)
final_train = next((float(entry["loss"]) for entry in reversed(history) if "loss" in entry), None)
report_lines = [
    f"# Training report: {{RUN_NAME}}", "",
    f"- Status: completed", f"- Base model: {{BASE_MODEL}}", f"- Dataset: {{DATASET_VERSION}}",
    f"- Seed: {{SEED}}", f"- Steps: {{trainer.state.global_step}}",
    f"- Best eval loss: {{best_eval}}", f"- Final train loss: {{final_train}}",
    f"- Best checkpoint: {{best_path}}", f"- Adapter: {{OUTPUT_DIR / 'adapter'}}",
]
(OUTPUT_DIR / "report.md").write_text("\\n".join(report_lines) + "\\n", encoding="utf-8")

print(f"Training complete. Adapter saved to {{OUTPUT_DIR / 'adapter'}}")
'''



COLAB_TEMPLATE = (
    "#@title Install training dependencies\n"
    "import subprocess, sys\n"
    "subprocess.check_call([sys.executable, '-m', 'pip', 'install', '-q', 'torch', 'transformers', 'peft', 'bitsandbytes', 'accelerate', 'pyyaml'])\n"
    "#@title Training script\n"
    + TRAIN_SCRIPT_TEMPLATE
)


def generate_script(cfg: TrainingConfig, output_path: str | Path, colab: bool = False) -> str:
    """Generate a training script from config."""
    from backend.app import config as app_config
    from backend.app.services import datasets as ds_service

    dataset_dir = ds_service.dataset_dir(cfg.dataset_version)
    if not dataset_dir.is_absolute():
        dataset_dir = app_config.ROOT / dataset_dir

    template = COLAB_TEMPLATE if colab else TRAIN_SCRIPT_TEMPLATE

    script = template.format(
        run_name=cfg.run_name,
        config_json=json.dumps(cfg.to_dict(), indent=2, ensure_ascii=False),
        config_yaml=cfg.run_name + ".yaml",
        load_in_4bit=str(cfg.quantization.load_in_4bit),
        quant_type=cfg.quantization.quant_type,
        double_quant=str(cfg.quantization.double_quant),
        lora_r=cfg.lora.r,
        lora_alpha=cfg.lora.alpha,
        lora_dropout=cfg.lora.dropout,
        target_modules=repr(cfg.lora.target_modules),
        epochs=cfg.train.epochs,
        batch_size=cfg.train.per_device_batch_size,
        grad_accum=cfg.train.grad_accum,
        learning_rate=cfg.train.learning_rate,
        lr_scheduler=cfg.train.lr_scheduler,
        warmup_ratio=cfg.train.warmup_ratio,
        eval_steps=cfg.train.eval_steps,
        save_steps=cfg.train.save_steps,
        early_stopping_patience=cfg.train.early_stopping_patience,
        max_seq_length=cfg.train.max_seq_length,
        loss_masking=cfg.loss_masking,
        dataset_dir=str(dataset_dir),
    )

    output = Path(output_path)
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(script, encoding="utf-8")
    output.chmod(0o755)
    return script


def main():
    parser = argparse.ArgumentParser(description="Generate training script from config YAML")
    parser.add_argument("--config", required=True, help="Path to config YAML")
    parser.add_argument("--output", default=None, help="Output path (default: runs/<run_name>/train.py)")
    parser.add_argument("--colab", action="store_true", help="Generate Colab notebook variant")
    args = parser.parse_args()

    cfg = TrainingConfig.load_yaml(args.config)
    errors = cfg.validate()
    if errors:
        print("Config validation failed:")
        for e in errors:
            print(f"  - {e}")
        sys.exit(1)

    if args.output:
        output_path = args.output
    else:
        output_path = f"runs/{cfg.run_name}/train.py"

    generate_script(cfg, output_path, colab=args.colab)
    print(f"Generated: {output_path}")


if __name__ == "__main__":
    main()
